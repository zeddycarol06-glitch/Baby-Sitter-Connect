interface BookingSeedInput {
  id: string;
  parentId: string;
  parentName: string;
  parentAvatarUrl: string;
  sitterId: string;
  childIds: string[];
  childNames: string[];
  date: string;
  startTime: string;
  endTime: string;
  status: Booking["status"];
  notes?: string;
  address: string;
  hasReview?: boolean;
  cancellationReason?: string;
  createdAt: string;
}

function makeBooking(input: BookingSeedInput): Booking {
  const sitter = seedSitters.find((item) => item.id === input.sitterId);
  if (!sitter) throw new Error(`Unknown sitter ${input.sitterId}`);
  const price = calculatePrice(sitter.hourlyRate, input.startTime, input.endTime);
  return {
    ...input,
    sitterUserId: sitter.userId,
    sitterName: sitter.displayName,
    hourlyRate: sitter.hourlyRate,
    subtotal: price.subtotal,
    serviceFee: price.serviceFee,
    total: price.total,
    hours: price.hours,
    createdAt: input.createdAt,
    updatedAt: input.createdAt,
  };
}

