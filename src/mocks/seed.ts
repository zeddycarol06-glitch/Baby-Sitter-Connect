const now = new Date();

function dateOffset(days: number): string {
  return format(addDays(now, days), "yyyy-MM-dd");
}

function isoOffset(days: number, hours = 0): string {
  return new Date(now.getTime() + days * 86_400_000 + hours * 3_600_000).toISOString();
}

function availability(sitterId: string, config: Record<number, [string, string]>): Availability[] {
  return Array.from({ length: 7 }, (_, day) => {
    const window = config[day];
    return {
      id: `avl_${sitterId}_${day}`,
      sitterId,
      dayOfWeek: day,
      startTime: window?.[0] ?? "08:00",
      endTime: window?.[1] ?? "18:00",
      isAvailable: Boolean(window),
    };
  });
}

